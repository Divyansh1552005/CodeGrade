import { Router } from 'express';
import Doubt from '../models/Doubt.js';
import Answer from '../models/Answer.js';
import { requireAuth } from '../middleware/auth.js';
import { requireRole } from '../middleware/roleGuard.js';
import { validate } from '../middleware/validate.js';
import { httpError } from '../middleware/errorHandler.js';
import { ensureWork } from '../services/workService.js';
import { createDoubtSchema, pageQuerySchema } from '../validation/schemas.js';
import { parseCursor } from '../utils/pagination.js';
import { z } from 'zod';
import { objectId } from '../validation/schemas.js';
import { markOffTopicByTeacher } from '../services/doubtTriage.js';
import {
  listDoubts, STATUS_FILTERS, findVisibleDoubt, listManualAnswerQueue, presentDoubt, findRemovedForOwner, presentRemoved, requestAppeal,
} from '../services/doubtAccess.js';
import Problem from '../models/Problem.js';
import { features } from '../config/features.js';
import { aiLimits } from '../config/aiLimits.js';
import { consumeDaily } from '../services/usageCounter.js';

const router = Router();

// POST /doubts  { title, body }  — students only. Posts immediately; the AI
// draft is generated by a durable worker job and the doubt's aiDraftStatus updates.
// Zod enforces both presence and the length caps that used to guard the LLM
// call (injection/DoS mitigation) — see validation/schemas.js.
router.post(
  '/',
  requireAuth,
  requireRole('student'),
  validate(createDoubtSchema),
  async (req, res, next) => {
    try {
      const { title, body, problemId, code } = req.body;
      if (problemId && !(await Problem.exists({ _id: problemId, archived: { $ne: true } }))) {
        throw httpError(404, 'Problem not found');
      }

      const triage = features.aiTriage();
      if (triage) {
        // Daily cap, counted atomically before anything is created. Every doubt counts,
        // including ones triage later removes. A blocked request creates nothing.
        const { maxDoubtsPerDay } = aiLimits().triage;
        const slot = await consumeDaily({ userId: req.user._id, kind: 'doubt', max: maxDoubtsPerDay });
        if (!slot.allowed) {
          const retryAfterSeconds = Math.max(1, Math.ceil((slot.resetAt.getTime() - Date.now()) / 1000));
          res.set('Retry-After', String(retryAfterSeconds));
          return res.status(429).json({
            error: `You can post at most ${maxDoubtsPerDay} doubts a day. You can post again after the daily reset.`,
            retryAfterSeconds, resetAt: slot.resetAt,
          });
        }
      }

      const doubt = await Doubt.create({
        studentId: req.user._id,
        title,
        body,
        ...(problemId ? { problemId } : {}),
        ...(code ? { code } : {}),
        // With triage off the doubt is created exactly as before, with no status.
        ...(triage ? { status: 'pending_triage' } : {}),
        aiDraftStatus: 'pending',
      });

      // Durable outbox rows; the worker does the AI calls. With triage on, the draft is
      // queued only after triage lets the doubt through.
      if (triage) {
        await ensureWork({ key: `triage-${doubt.id}`, type: 'doubt-triage', ownerId: req.user._id,
          payload: { doubtId: doubt.id, requestId: req.id } });
      } else {
        await ensureWork({ key: `draft-${doubt.id}`, type: 'doubt-draft',
          ownerId: req.user._id, payload: { doubtId: doubt.id } });
      }

      res.status(201).json({ doubt: presentDoubt(doubt, req.user) });
    } catch (err) {
      next(err);
    }
  }
);

// GET /doubts[?mine=1][&status=][&limit=10&cursor=...]  — shared board (list), or (with
// `mine`) just the requesting user's own doubts — used by the profile page. Always paged
// (default 10, at most 50) with light rows (a `preview`, not the body). A bad limit or cursor is a 400.
// Each doubt is annotated with `hasApprovedAnswer` so the list can render a
// status badge without N+1 calls. What a viewer may see is decided in one place,
// services/doubtAccess.js: auto-rejected doubts never appear here for anyone.
// Optional `status` filter: answered, awaiting_review or awaiting_teacher.
const listQuery = pageQuerySchema.extend({ status: z.enum(STATUS_FILTERS).optional(), mine: z.string().max(10).optional() });
router.get('/', requireAuth, validate(listQuery, 'query'), async (req, res, next) => {
  try {
    res.json(await listDoubts({ viewer: req.user, mine: Boolean(req.query.mine), status: req.query.status, limit: req.query.limit, cursor: parseCursor(req.query.cursor) }));
  } catch (err) {
    next(err);
  }
});

// GET /doubts/failed  — teacher-only: doubts with no AI-drafted answer (either
// a genuine AI failure, or the doubt was judged off-topic/non-programming)
// that do not yet have any answer, so they need a manual decision. (Declared
// before the '/:id' route so it isn't captured as an id.)
router.get('/failed', requireAuth, requireRole('teacher'), async (req, res, next) => {
  try {
    const doubts = await listManualAnswerQueue(req.user);
    res.json({ doubts: doubts.map((d) => presentDoubt(d, req.user)) });
  } catch (err) {
    next(err);
  }
});

// POST /doubts/:id/off-topic  { reason? }  — a teacher marks a doubt off topic, usually while answering it.
// The doubt is hidden from the board, the student is told and can appeal once (not again if the appeal
// was already used). A doubt that already has an approved answer cannot be marked.
router.post(
  '/:id/off-topic',
  requireAuth,
  requireRole('teacher'),
  validate(z.object({ id: objectId }), 'params'),
  validate(z.object({ reason: z.string().trim().max(aiLimits().triage.reasonMaxChars).optional() })),
  async (req, res, next) => {
    try {
      const visible = await findVisibleDoubt(req.params.id, req.user);
      if (!visible) throw httpError(404, 'Doubt not found');
      const outcome = await markOffTopicByTeacher(req.params.id, req.user, req.body.reason);
      if (outcome.error === 'answered') throw httpError(409, 'This doubt already has an approved answer, so it cannot be marked off topic.');
      if (outcome.error) throw httpError(404, 'Doubt not found');
      req.log?.info('doubt.off_topic.by_teacher', { doubtId: String(visible._id) });
      res.json({ removed: true, doubtId: String(visible._id) });
    } catch (err) {
      next(err);
    }
  }
);

// GET /doubts/:id/removed  — the author's own removed doubt, with the reason. Not linked from
// any list; students reach it from the removal notification. Everyone else, including
// teachers, and any doubt that was not removed, gets the same 404.
router.get('/:id/removed', requireAuth, async (req, res, next) => {
  try {
    const doubt = await findRemovedForOwner(req.params.id, req.user._id);
    if (!doubt) throw httpError(404, 'Doubt not found');
    res.json({ doubt: presentRemoved(doubt) });
  } catch (err) {
    next(err);
  }
});

// POST /doubts/:id/appeal  — the author asks for a teacher to review a removed doubt. One
// appeal per doubt. The doubt becomes `appealed` and goes straight to the teachers' manual-answer
// queue, with no AI draft, in one atomic update (so it enters the queue exactly once). From then on
// it follows the normal visibility rules.
router.post('/:id/appeal', requireAuth, requireRole('student'), async (req, res, next) => {
  try {
    const outcome = await requestAppeal(req.params.id, req.user._id);
    if (!outcome) throw httpError(404, 'Doubt not found');
    if (outcome.already) throw httpError(409, 'You have already asked for a teacher to review this doubt.');
    req.log?.info('doubt.appeal.requested', { doubtId: outcome.doubt.id });
    res.json({ doubt: presentRemoved(outcome.doubt) });
  } catch (err) {
    next(err);
  }
});

// GET /doubts/:id
router.get('/:id', requireAuth, async (req, res, next) => {
  try {
    const doubt = await findVisibleDoubt(req.params.id, req.user);
    if (!doubt) throw httpError(404, 'Doubt not found');
    res.json({ doubt: presentDoubt(doubt, req.user) });
  } catch (err) {
    next(err);
  }
});

// GET /doubts/:id/answer  — students only ever see an APPROVED answer.
router.get('/:id/answer', requireAuth, async (req, res, next) => {
  try {
    const doubt = await findVisibleDoubt(req.params.id, req.user);
    if (!doubt) throw httpError(404, 'Doubt not found');

    const answer = await Answer.findOne({
      doubtId: doubt._id,
      state: 'approved',
    })
      .sort({ reviewedAt: -1 })
      // Include the teacher who approved/authored it, to show "answered by …".
      .populate('reviewedBy', 'name');

    // No approved answer yet -> nothing visible to the student.
    res.json({ answer: answer || null });
  } catch (err) {
    next(err);
  }
});

export default router;
